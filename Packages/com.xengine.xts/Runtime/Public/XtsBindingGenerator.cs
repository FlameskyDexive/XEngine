using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace XEngine.XTS.Binding;

/// <summary>
/// Build-time generation over a validated <see cref="XtsBindingRegistry"/>:
/// the TypeScript declarations (`.d.ts`) and the JS glue module that adapts
/// the raw global callbacks into the typed `xengine` virtual module.
/// Generation is text-only and reflection-free (types are declared in the
/// specs), so it can run in the editor and in build pipelines.
/// </summary>
public static class XtsBindingGenerator
{
    /// <summary>Generate `xengine-bindings.d.ts` content for the registry.</summary>
    public static string GenerateDeclarations(XtsBindingRegistry registry)
    {
        var sb = new StringBuilder();
        sb.AppendLine("/* Generated by XTS — do not edit. Regenerate via the XTS editor command. */");
        sb.AppendLine();
        foreach (var spec in registry.Functions)
        {
            if (!string.IsNullOrEmpty(spec.Description))
                sb.AppendLine($"/** {spec.Description} */");
            var parameters = string.Join(", ", spec.Parameters.Select(p =>
                $"{p.Name}: {XtsBindingTypeMap.ToTypeScript(p.Type, p.ClrType)}"));
            var ret = XtsBindingTypeMap.ToTypeScript(spec.ReturnType);
            sb.AppendLine($"declare function {spec.GlobalName}({parameters}): {ret};");
            sb.AppendLine();
        }
        return sb.ToString();
    }

    /// <summary>
    /// Generate the JS glue module: re-exports every global callback under its
    /// stable binding id and handles the JSON channel (stringify in, parse
    /// out) so complex values cross by value.
    /// </summary>
    public static string GenerateGlueModule(XtsBindingRegistry registry)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// Generated by XTS — do not edit.");
        sb.AppendLine();
        foreach (var spec in registry.Functions)
        {
            var jsonIn = spec.Parameters.Where(p => p.Type == XtsBindingType.Json).Select(p => p.Name).ToHashSet();
            var jsonOut = spec.ReturnType == XtsBindingType.Json;

            var call = spec.GlobalName;
            var parameters = string.Join(", ", spec.Parameters.Select(p => p.Name));
            var forwarded = string.Join(", ", spec.Parameters.Select(p =>
                jsonIn.Contains(p.Name) ? $"JSON.stringify({p.Name})" : p.Name));
            var body = jsonOut
                ? $"return JSON.parse({call}({forwarded}));"
                : $"return {call}({forwarded});";
            var exportName = ExportNameFromBindingId(spec.BindingId);
            sb.AppendLine($"export function {exportName}({parameters}) {{");
            sb.AppendLine($"    {body}");
            sb.AppendLine("}");
        }
        return sb.ToString();
    }

    /// <summary>Binding id "engine.time.deltaTime" exports as "deltaTime" (last segment).</summary>
    public static string ExportNameFromBindingId(string bindingId)
    {
        var last = bindingId.LastIndexOf('.');
        return last >= 0 ? bindingId[(last + 1)..] : bindingId;
    }

    /// <summary>
    /// Generate the host capability manifest consumed by content activation:
    /// the content's manifest lists binding ids it requires; activation
    /// refuses when the host capability set does not cover them.
    /// </summary>
    public static string GenerateCapabilityManifest(XtsBindingRegistry registry, string hostVersion)
    {
        var document = new
        {
            schema = "xengine.xts.capabilities.v1",
            hostVersion,
            bindings = registry.Functions
                .OrderBy(f => f.BindingId, StringComparer.Ordinal)
                .Select(f => new
                {
                    id = f.BindingId,
                    global = f.GlobalName,
                    parameters = f.Parameters.Select(p => new
                    {
                        name = p.Name,
                        type = p.Type.ToString(),
                        tsType = XtsBindingTypeMap.ToTypeScript(p.Type, p.ClrType),
                    }).ToArray(),
                    returns = f.ReturnType.ToString(),
                }).ToArray(),
        };
        return JsonSerializer.Serialize(document, new JsonSerializerOptions { WriteIndented = true });
    }

    /// <summary>
    /// Verify a content manifest's required binding ids against the host
    /// capability manifest. Returns the list of problems; empty means the
    /// content may activate. Unknown ids and version mismatches are hard
    /// failures — there is no reflection fallback.
    /// </summary>
    public static List<string> VerifyCapabilityRequirements(string hostCapabilityJson, IEnumerable<string> requiredBindingIds)
    {
        var errors = new List<string>();
        JsonDocument document;
        try
        {
            document = JsonDocument.Parse(hostCapabilityJson);
        }
        catch (JsonException e)
        {
            return new List<string> { $"host capability manifest is not valid JSON: {e.Message}" };
        }

        var available = new HashSet<string>(StringComparer.Ordinal);
        if (document.RootElement.TryGetProperty("bindings", out var bindings) &&
            bindings.ValueKind == JsonValueKind.Array)
        {
            foreach (var binding in bindings.EnumerateArray())
            {
                if (binding.TryGetProperty("id", out var id) && id.ValueKind == JsonValueKind.String)
                    available.Add(id.GetString()!);
            }
        }
        else
        {
            errors.Add("host capability manifest has no bindings array");
        }

        foreach (var required in requiredBindingIds)
        {
            if (!available.Contains(required))
                errors.Add($"content requires binding '{required}' which this host does not provide");
        }
        return errors;
    }
}
