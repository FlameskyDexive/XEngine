using System;
using System.Text;
using System.Text.Json;

namespace XEngine.Editor.Build.HarmonyOS;

/// <summary>Writes generated reachability roots for Safe-mode HarmonyOS trimming.</summary>
internal static class HarmonyOSManagedTrimRoots
{
    internal const string SourceFileName = "XEngine.HarmonyOS.PlayerRoots.g.cs";

    internal static string CreateSource(HarmonyOSManagedTypeRootCollection collection)
    {
        ArgumentNullException.ThrowIfNull(collection);
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.AppendLine("using System.Diagnostics.CodeAnalysis;");
        source.AppendLine();
        source.AppendLine("namespace XEngine.Generated.HarmonyOS;");
        source.AppendLine();
        source.AppendLine("internal static class XEnginePlayerRoots");
        source.AppendLine("{");
        for (int i = 0; i < collection.Types.Count; i++)
        {
            HarmonyOSManagedTypeRoot root = collection.Types[i];
            source.Append("    [DynamicDependency(DynamicallyAccessedMemberTypes.All, ");
            source.Append(JsonSerializer.Serialize(root.TypeName));
            source.Append(", ");
            source.Append(JsonSerializer.Serialize(root.AssemblyName));
            source.AppendLine(")]");
        }
        source.AppendLine("    internal static void Preserve() { }");
        source.AppendLine("}");
        return source.ToString();
    }
}
