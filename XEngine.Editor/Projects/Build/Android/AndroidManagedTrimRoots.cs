using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.Json;
using System.Xml.Linq;

namespace XEngine.Editor.Build.Android;

/// <summary>
/// Writes the conservative Safe-mode linker roots used by generated Android projects.
/// Safe keeps managed engine/user/plugin assemblies intact while allowing the Android
/// SDK linker to remove framework code that is outside the observed closure.
/// </summary>
internal static class AndroidManagedTrimRoots
{
    internal const string DescriptorFileName = "XEngine.Android.linker.xml";
    internal const string SourceFileName = "XEngine.PlayerRoots.g.cs";

    internal static string CreateSource(AndroidManagedTypeRootCollection collection)
    {
        ArgumentNullException.ThrowIfNull(collection);
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.AppendLine("using System.Diagnostics.CodeAnalysis;");
        source.AppendLine();
        source.AppendLine("namespace XEngine.Generated.Android;");
        source.AppendLine();
        source.AppendLine("internal static class XEnginePlayerRoots");
        source.AppendLine("{");
        for (int i = 0; i < collection.Types.Count; i++)
        {
            AndroidManagedTypeRoot root = collection.Types[i];
            source.Append("    [DynamicDependency(DynamicallyAccessedMemberTypes.All, ");
            source.Append(JsonSerializer.Serialize(ToLinkerTypeName(root.TypeName)));
            source.Append(", ");
            source.Append(JsonSerializer.Serialize(root.AssemblyName));
            source.AppendLine(")]");
        }
        source.AppendLine("    internal static void Preserve()");
        source.AppendLine("    {");
        if (collection.Types.Count == 0)
        {
            source.AppendLine("        global::XEngine.Runtime.RuntimeTypeRegistry.ConfigureGenerated();");
        }
        else
        {
            source.AppendLine("        global::XEngine.Runtime.RuntimeTypeRegistry.ConfigureGenerated(");
            for (int i = 0; i < collection.Types.Count; i++)
            {
                AndroidManagedTypeRoot root = collection.Types[i];
                source.Append("            ");
                source.Append(JsonSerializer.Serialize(root.TypeName + ", " + root.AssemblyName));
                source.AppendLine(i + 1 == collection.Types.Count ? ");" : ",");
            }
        }
        source.AppendLine("    }");
        source.AppendLine("}");
        return source.ToString();
    }

    private static string ToLinkerTypeName(string runtimeTypeName) => runtimeTypeName.Replace('+', '/');

    internal static void WriteDescriptor(
        string path,
        string generatedAssemblyName,
        AndroidManagedDependencyCollection? dependencies)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(path);
        ArgumentException.ThrowIfNullOrWhiteSpace(generatedAssemblyName);

        var assemblyNames = new SortedSet<string>(StringComparer.Ordinal)
        {
            generatedAssemblyName,
        };
        if (dependencies != null)
        {
            for (int i = 0; i < dependencies.Assemblies.Count; i++)
            {
                string name = dependencies.Assemblies[i].Name.Trim();
                if (name.Length > 0)
                    assemblyNames.Add(name);
            }
        }

        var document = new XDocument(
            new XDeclaration("1.0", "utf-8", null),
            new XElement(
                "linker",
                new XComment(
                    "Generated Safe-mode roots. User/runtime assemblies stay intact so serialized and " +
                    "reflection-created types remain available; framework trimming remains linker-owned."),
                CreateAssemblyElements(assemblyNames)));

        string? directory = Path.GetDirectoryName(Path.GetFullPath(path));
        if (directory != null)
            Directory.CreateDirectory(directory);
        File.WriteAllText(path, document.ToString(SaveOptions.None) + Environment.NewLine, new UTF8Encoding(false));
    }

    private static IEnumerable<XElement> CreateAssemblyElements(IEnumerable<string> names)
    {
        foreach (string name in names)
        {
            yield return new XElement(
                "assembly",
                new XAttribute("fullname", name),
                new XAttribute("preserve", "all"));
        }
    }
}
